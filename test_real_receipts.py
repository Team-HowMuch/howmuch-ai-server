def test_one_item_read_as_two_coordinate_rows_keeps_its_sub_row_discount():
    """배달앱 전표: 이름이 줄바꿈된 품목이 좌표 줄 둘(금액 36,000 이 두 번)로 읽힌다.

    둘째 줄에 `동은어후 -2,500`(= 할인) 서브 줄이 달려 있다. 둘째 줄이 첫째 줄에 이미 짝지어진 VLM 품목을
    다시 못 쓰게 막으면 그 할인이 사라져 앱이 36,000 원을 낸 것으로 계산한다(실제 33,500).
    """
    merged, _ = _merge(_BAEMIN_SET_OCR, _BAEMIN_SET_VLM)
    assert [(i["price"], i["discount"]) for i in merged["items"]] == [(36000, 2500)]
    assert merged["total_amount"] == 33500
    assert merged["items_verified"] is True


